#!/usr/bin/env node
// Regenerates hevc/scaling_golden.mbt: 7.4.5 scaling-list factor fixtures.
//
// The truth comes from tools/scaling_truth.json, produced by copying
// tools/export_scaling_truth_test.go into a gen2brain/h265 checkout and
// reading the REAL upstream sps.scalingList after DecodeNAL, then calling
// the upstream unexported scalingList.factors() (7.4.5). Two streams are
// captured: scaling_list.h265 (SPS scaling list) and
// signhide_scaling_320x240.h265 (default intra/inter matrices).
//
// tools/crosscheck_scaling.mjs re-derives every factor from an independent
// JS transcription of 7.4.5 (no Go/network), so a hand edit fails CI.
//
//   node tools/gen_scaling_golden.mjs            # rewrite the fixture
//   node tools/gen_scaling_golden.mjs --check    # verify it is current

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execFileSync } from 'child_process';
import os from 'os';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const raw = JSON.parse(fs.readFileSync(path.join(root, 'tools/scaling_truth.json'), 'utf8'));
const check = process.argv.includes('--check');

function intLit(arr, indent) {
  const out = [];
  for (let i = 0; i < arr.length; i += 9)
    out.push(indent + arr.slice(i, i + 9).join(', ') + ',');
  return out.join('\n') || indent;
}

const L = [];
L.push('// 7.4.5 scaling-list factor fixtures, generated by');
L.push('// tools/gen_scaling_golden.mjs from tools/scaling_truth.json (the REAL');
L.push('// upstream Go sps.scalingList + scalingList.factors()).');
L.push('');
L.push('///|');
L.push('/// One captured scaling list: raw sl[4][6][16], dc[2][6], and the');
L.push('/// derived factors[4][6][n*n] of 7.4.5.');
L.push('pub(all) struct ScalingCase {');
L.push('  name : String');
L.push('  sl : Array[Array[Array[Int32]]]');
L.push('  dc : Array[Array[Int32]]');
L.push('  factors : Array[Array[Array[Int32]]]');
L.push('}');
L.push('');
L.push('///|');
L.push(`/// ${Object.keys(raw).length} upstream scaling lists.`);
L.push('pub let scaling_cases : Array[ScalingCase] = [');
for (const [name, c] of Object.entries(raw)) {
  L.push('  {');
  L.push(`    name: ${JSON.stringify(name)},`);
  L.push('    sl: [');
  for (const m of c.sl) {
    L.push('      [');
    for (const a of m) { L.push('        ['); L.push(intLit(a, '          ')); L.push('        ],'); }
    L.push('      ],');
  }
  L.push('    ],');
  L.push('    dc: [');
  for (const a of c.dc) { L.push('      ['); L.push(intLit(a, '        ')); L.push('      ],'); }
  L.push('    ],');
  L.push('    factors: [');
  for (const m of c.factors) {
    L.push('      [');
    for (const a of m) { L.push('        ['); L.push(intLit(a, '          ')); L.push('        ],'); }
    L.push('      ],');
  }
  L.push('    ],');
  L.push('  },');
}
L.push(']');
L.push('');

const out = L.join('\n');

// moon fmt rewraps long array literals (column width). The committed golden
// is the formatted form, so --check must compare against a formatted copy of
// the generated text rather than the raw text. Format a temp file through the
// real formatter; generate mode formats the target in place.
function formatted(text) {
  // Format inside the package: moon fmt only applies its ///| block
  // splitting and column-width rewrapping when the file is in a package.
  const tmp = path.join(root, 'hevc', `_m3golden_fmt_${process.pid}.mbt`);
  fs.writeFileSync(tmp, text);
  try {
    execFileSync('moon', ['fmt', tmp], { stdio: 'ignore' });
  } catch (e) {
    // A standalone .mbt outside a package may not format; fall back to the
    // raw text (the golden uses ///| blocks, which fmt leaves as-is when the
    // arrays are already short enough).
  }
  const r = fs.readFileSync(tmp, 'utf8');
  fs.unlinkSync(tmp);
  return r;
}

const target = path.join(root, 'hevc/scaling_golden.mbt');
if (check) {
  const cur = fs.readFileSync(target, 'utf8');
  if (formatted(out) !== cur) {
    console.error(`${target} is stale; run node ${path.basename(process.argv[1])}`);
    process.exit(1);
  }
  console.log(`scaling golden OK (${Object.keys(raw).length} cases)`);
} else {
  fs.writeFileSync(target, out);
  try { execFileSync('moon', ['fmt', target], { stdio: 'ignore' }); } catch (e) {}
  console.log(`wrote ${target} (${Object.keys(raw).length} cases)`);
}
