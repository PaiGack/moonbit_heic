// --check verifies DATA, not bytes: moon fmt may reflow literals, so compare
// the ordered numeric/boolean/hex payload extracted from the data section with
// the authoritative truth rebuilt from the Go JSON.
function numericFingerprint(text) {
  const toks = [];
  const start = text.indexOf('pub let mpm_cases');
  if (start < 0) throw new Error('no data section in golden.mbt');
  const body = text.slice(start)
    .split('\n')
    .filter(l => !l.trim().startsWith('//') && !l.includes('pub let ') &&
                 !l.includes('pub(all) struct'))
    .join('\n');
  const re = /\b(true|false)\b|b'\\x([0-9a-f]{2})'|(?<![A-Za-z0-9_])(-?\d+)(?![A-Za-z0-9_])/g;
  let m;
  while ((m = re.exec(body)) !== null) {
    if (m[1] !== undefined) toks.push(m[1]);
    else if (m[2] !== undefined) toks.push('x' + m[2]);
    else toks.push(m[3]);
  }
  return toks;
}
function truthFingerprint() {
  const t = [];
  const push = (...xs) => { for (const x of xs) t.push(String(x)); };
  for (const c of g.mpm) push(c.A, c.B, ...c.Want);
  for (const c of g.split_cu_ctx) push(c.LeftDepth, c.AboveDepth, c.Depth, c.Want);
  for (const c of g.ctx_idx) push(kindOf(c.Kind), c.A, c.Want);
  for (const v of g.chroma422) push(v);
  for (const v of g.chroma_qp) push(v);
  for (const c of g.qp_wrap) push(c.Pred, c.Delta, c.Want);
  for (const c of g.sao_cmax) push(c.BitDepth, c.Want);
  for (const c of g.luma_cases) {
    push(...c.Cand, c.Mode);
    for (const z of b64(c.Bytes)) push('x' + z.toString(16).padStart(2, '0'));
    push(c.Want);
  }
  for (const c of g.chroma_cases) {
    push(c.Luma);
    for (const z of b64(c.Bytes)) push('x' + z.toString(16).padStart(2, '0'));
    push(c.Want);
  }
  for (const c of g.qpd_cases) {
    for (const z of b64(c.Bytes)) push('x' + z.toString(16).padStart(2, '0'));
    push(c.Want);
  }
  for (const c of g.cqo_cases) {
    push(c.Len, ...c.CbList, ...c.CrList);
    for (const z of b64(c.Bytes)) push('x' + z.toString(16).padStart(2, '0'));
    push(c.WantCb, c.WantCr);
  }
  for (const c of g.part_cases) {
    for (const z of b64(c.Bytes)) push('x' + z.toString(16).padStart(2, '0'));
    push(c.Want);
  }
  for (const c of g.bin_cases) {
    push(c.Ctx);
    for (const z of b64(c.Bytes)) push('x' + z.toString(16).padStart(2, '0'));
    push(c.Want);
  }
  for (const c of g.sao_cases) {
    for (const z of b64(c.Bytes)) push('x' + z.toString(16).padStart(2, '0'));
    push(...c.Types);
    for (const o of c.Offs) push(...o);
    push(...c.Bands, ...c.Classes);
  }
  return t;
}

if (check) {
  const current = fs.readFileSync(target, 'utf8');
  const got = numericFingerprint(current);
  const want = truthFingerprint();
  if (got.length !== want.length) {
    console.error(`hevc/syntax/golden.mbt payload length ${got.length}, expected ${want.length}`);
    process.exit(1);
  }
  for (let i = 0; i < want.length; i++) {
    if (got[i] !== want[i]) {
      console.error(`hevc/syntax/golden.mbt drift at token ${i}: got ${got[i]}, want ${want[i]}`);
      process.exit(1);
    }
  }
  console.log(`gen_syntax_golden --check: ${want.length} tokens current (${g.luma_cases.length} luma, ${g.sao_cases.length} SAO, ${g.bin_cases.length} bin bitstreams)`);
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, generated);
  console.log(`wrote ${target}: ${g.mpm.length} mpm, ${g.luma_cases.length} luma, ${g.chroma_cases.length} chroma, ${g.qpd_cases.length} qpd, ${g.cqo_cases.length} cqo, ${g.sao_cases.length} sao cases`);
}
