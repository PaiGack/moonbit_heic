#!/usr/bin/env node
// Regenerates hevc/loopfilter/deblock_golden.mbt: end-to-end whole-frame
// deblocking fixtures for decode_i_frame's frame-level 8.7.2 pass.
//
// The fixture data comes from tools/deblock_golden.json, produced by the REAL
// upstream Go decoder (tools/export_deblock_golden_test.go, run in a
// gen2brain/h265 checkout with -tags noasm). For each single-slice I frame the
// exporter:
//   - decodes the stream with DecodeNAL + Flush into the final planar YUV
//     (WITH upstream deblock()/applySAO() => `full`),
//   - decodes the same stream with the loop filters disabled (`plain`),
//   - captures the real ctuDecoder deblock state just before deblock() runs:
//     the 4x4-raster intra/cbf/tuV/tuH/puV/puH block flags, per-block qpY
//     and noFilter (a test-only hook in finishPicture),
//   - asserts `full` equals the shipped *_ref.yuv where one exists.
//
// The MoonBit decode_i_frame must reproduce `full` byte for byte. `plain` is
// the CTU reconstruction alone (filters off); a case where full != plain is
// proof the frame-level deblock driver really changed pixels rather than
// being a no-op. tools/crosscheck_deblock.mjs pins the fixture fingerprints
// and re-derives the changed-sample count from full/plain independently.
// CI needs no Go/network.
//
//   node tools/gen_deblock_golden.mjs            # rewrite the fixture
//   node tools/gen_deblock_golden.mjs --check    # verify it is current
//
// Self-contained: reads only the committed JSON and re-emits MoonBit literals.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const raw = JSON.parse(fs.readFileSync(path.join(root, 'tools/deblock_golden.json'), 'utf8'));
const check = process.argv.includes('--check');

const b64 = s => Array.from(Buffer.from(s, 'base64'));
const boolLit = v => v ? 'true' : 'false';
function bytesLit(arr, indent) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + arr.slice(i, i + 16).map(b => `b'\\x${b.toString(16).padStart(2, '0')}'`).join(', ') + ',');
  return lines.join('\n') || indent;
}
function bytesVal(arr, _indent) {
  // A byte-string literal is stable under `moon fmt` (an Array literal of
  // byte elements gets reflowed), so the generated fixture matches what CI's
  // `moon fmt --check` expects.
  return 'b"' + arr.map(b => `\\x${b.toString(16).padStart(2, '0')}`).join('') + '"';
}
function boolArr(arr, indent) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + '  ' + arr.slice(i, i + 16).map(boolLit).join(', ') + ',');
  return `[${lines.length ? '\n' + lines.join('\n') + '\n' + indent : ''}]`;
}
function intArr(arr, indent) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + '  ' + arr.slice(i, i + 16).map(v => `${v}`).join(', ') + ',');
  return `[${lines.length ? '\n' + lines.join('\n') + '\n' + indent : ''}]`;
}

const L = [];
L.push('// Golden fixtures for the frame-level 8.7.2 deblocking pass of');
L.push('// decode_i_frame. Generated by tools/gen_deblock_golden.mjs from');
L.push('// tools/deblock_golden.json (the REAL upstream Go decoder, -tags noasm).');
L.push('// Each case is a complete Annex B single-slice I frame, the exact planar');
L.push('// Y/Cb/Cr output WITH upstream deblocking (`full`), the same output with');
L.push('// the loop filters disabled (`plain`), and the real 4x4-raster block state');
L.push('// the upstream ctuDecoder fed to deblock() (a test-only hook). MoonBit');
L.push('// decode_i_frame must reproduce `full` byte for byte; full != plain is');
L.push('// proof the frame-level driver changed real pixels.');
L.push('');
L.push('///|');
L.push('/// One whole I frame plus the authoritative filtered / unfiltered YUV.');
L.push('pub(all) struct DeblockCase {');
L.push('  name : String');
L.push('  stream : Bytes');
L.push('  width : Int32');
L.push('  height : Int32');
L.push('  full : Bytes');
L.push('  plain : Bytes');
L.push('  beta_off : Int32');
L.push('  tc_off : Int32');
L.push('  deblock_disabled : Bool');
L.push('  has_ref : Bool');
L.push('  changed : Int32');
L.push('}');
L.push('');
L.push('///|');
L.push(`/// ${raw.length} single-slice I frames. 1 has deblocking genuinely active`);
L.push('/// (full != plain); the rest are no-op regressions, 5 with an upstream');
L.push('/// *_ref.yuv asserted byte for byte by the exporter.');
L.push('pub let deblock_cases : Array[DeblockCase] = [');
for (const c of raw) {
  const full = b64(c.full), plain = b64(c.plain);
  let changed = 0;
  for (let i = 0; i < full.length; i++) if (full[i] !== plain[i]) changed++;
  L.push('  {');
  L.push(`    name: ${JSON.stringify(c.name)},`);
  L.push(`    stream: ${bytesVal(b64(c.stream), '    ')},`);
  L.push(`    width: ${c.w},`);
  L.push(`    height: ${c.h},`);
  L.push(`    full: ${bytesVal(full, '    ')},`);
  L.push(`    plain: ${bytesVal(plain, '    ')},`);
  L.push(`    beta_off: ${c.beta_off},`);
  L.push(`    tc_off: ${c.tc_off},`);
  L.push(`    deblock_disabled: ${boolLit(c.deblock_disabled)},`);
  L.push(`    has_ref: ${boolLit(c.has_ref)},`);
  L.push(`    changed: ${changed},`);
  L.push('  },');
}
L.push(']');
L.push('');

const out = L.join('\n');
const dest = path.join(root, 'hevc/loopfilter/deblock_golden.mbt');
if (check) {
  const cur = fs.existsSync(dest) ? fs.readFileSync(dest, 'utf8') : '';
  if (cur !== out) {
    console.error('deblock_golden.mbt is out of date; run node tools/gen_deblock_golden.mjs');
    process.exit(1);
  }
  console.log(`deblock_golden.mbt is current (${raw.length} cases)`);
} else {
  fs.writeFileSync(dest, out);
  console.log(`wrote ${dest} (${raw.length} cases)`);
}
