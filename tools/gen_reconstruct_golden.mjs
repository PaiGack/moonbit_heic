#!/usr/bin/env node
// Regenerates hevc/geometry/golden.mbt and hevc/reconstruct/golden.mbt:
// byte-exact fixtures for the M3 spatial-state and single-block-
// reconstruction layers.
//
// The fixture data comes from tools/reconstruct_golden.json, produced by the
// REAL upstream Go code (tools/export_reconstruct_golden_test.go, run in a
// gen2brain/h265 checkout with -tags noasm): buildMinTbAddr/available/
// predictQP/gatherRef drove the truth for the geometry half, and the real
// reconstructPlane (8.6.x) turned real cabacWriter/encodeResidual bitstreams
// into real pixels for the reconstruction half. tools/crosscheck_reconstruct.mjs
// holds the geometry half value-for-value against an independent from-the-spec
// JS transcription; the reconstruction half is checked by the MoonBit port,
// built from the independently byte-exact-checked @recon/@residual/@cabac
// kernels, reproducing those pixels sample for sample. CI needs no Go/network.
//
//   node tools/gen_reconstruct_golden.mjs            # rewrite both fixtures
//   node tools/gen_reconstruct_golden.mjs --check    # verify both are current
//
// Self-contained: reads only the committed JSON and re-emits MoonBit literals.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const g = JSON.parse(fs.readFileSync(path.join(root, 'tools/reconstruct_golden.json'), 'utf8'));
const check = process.argv.includes('--check');

const b64 = s => Array.from(Buffer.from(s, 'base64'));
const boolLit = v => v ? 'true' : 'false';
function bytesLit(arr, indent) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + arr.slice(i, i + 16).map(b => `b'\\x${b.toString(16).padStart(2, '0')}'`).join(', ') + ',');
  return lines.join('\n');
}
function intLit(arr, indent, width = 20) {
  const lines = [];
  for (let i = 0; i < arr.length; i += width)
    lines.push(indent + arr.slice(i, i + width).join(', ') + ',');
  return lines.join('\n');
}
function boolArr(arr, indent, width = 24) {
  const lines = [];
  for (let i = 0; i < arr.length; i += width)
    lines.push(indent + arr.slice(i, i + width).map(boolLit).join(', ') + ',');
  return lines.join('\n');
}

// ---------------------------------------------------------------------------
// geometry/golden.mbt
// ---------------------------------------------------------------------------
const G = [];
G.push('// Golden fixtures for the M3 spatial-state layer (6.5.2 / 6.4.1 / 8.6.1 / 8.4.4.2.2).');
G.push('// Generated by tools/gen_reconstruct_golden.mjs from tools/reconstruct_golden.json');
G.push('// (the real upstream Go code) and held value-for-value against an independent');
G.push('// JS transcription by tools/crosscheck_reconstruct.mjs.');
G.push('');

G.push('///|');
G.push('/// One whole 6.5.2 MinTbAddrZs table for a (ctbs_w x ctbs_h) single-tile picture.');
G.push('pub(all) struct MtaCase {');
G.push('  ctbs_w : Int32');
G.push('  ctbs_h : Int32');
G.push('  ctb_log2 : Int32');
G.push('  min_tb_log2 : Int32');
G.push('  addr : Array[Int32]');
G.push('}');
G.push('');
G.push('///|');
G.push('/// One 6.4.1 z-scan availability query.');
G.push('pub(all) struct AvailCase {');
G.push('  x_curr : Int32');
G.push('  y_curr : Int32');
G.push('  x_n : Int32');
G.push('  y_n : Int32');
G.push('  want : Bool');
G.push('}');
G.push('');
G.push('///|');
G.push('/// One 8.6.1 qPY_PRED query (predict at (8,8), ctb_log2=6).');
G.push('pub(all) struct QpCase {');
G.push('  qp_prev : Int32');
G.push('  qp_a : Int32');
G.push('  qp_b : Int32');
G.push('  want : Int32');
G.push('}');
G.push('');
G.push('///|');
G.push('/// One 8.4.4.2.2 gatherRef + substitute case.');
G.push('pub(all) struct RefCase {');
G.push('  x : Int32');
G.push('  y : Int32');
G.push('  n : Int32');
G.push('  c_idx : Int32');
G.push('  plane : Array[Int32]');
G.push('  cplane : Array[Int32]');
G.push('  samples : Array[Int32]');
G.push('  avail : Array[Bool]');
G.push('}');
G.push('');

G.push('///|');
G.push('/// 6.5.2 full MinTbAddrZs tables.');
G.push('pub let mta_cases : Array[MtaCase] = [');
for (const c of g.min_tb_addr) {
  G.push(`  { ctbs_w: ${c.CtbsW}, ctbs_h: ${c.CtbsH}, ctb_log2: ${c.CtbLog2}, min_tb_log2: ${c.MinTbLog2},`);
  G.push('    addr: [');
  G.push(intLit(c.Addr, '      '));
  G.push('    ] },');
}
G.push(']');
G.push('');

G.push('///|');
G.push('/// 6.4.1 availability, full sweep of (x_curr,y_curr) x neighbour offsets.');
G.push('pub let avail_cases : Array[AvailCase] = [');
for (const c of g.available)
  G.push(`  { x_curr: ${c.XCurr}, y_curr: ${c.YCurr}, x_n: ${c.XN}, y_n: ${c.YN}, want: ${boolLit(c.Want)} },`);
G.push(']');
G.push('');

G.push('///|');
G.push('/// 8.6.1 qPY_PRED over qp_prev / qp_a / qp_b combinations.');
G.push('pub let qp_cases : Array[QpCase] = [');
for (const c of g.predict_qp)
  G.push(`  { qp_prev: ${c.QpPrev}, qp_a: ${c.QpA}, qp_b: ${c.QpB}, want: ${c.Want} },`);
G.push(']');
G.push('');

G.push('///|');
G.push('/// 8.4.4.2.2 gatherRef (ref.s after substitute) + availability, planar.');
G.push('pub let ref_cases : Array[RefCase] = [');
for (const c of g.gather_ref) {
  G.push(`  { x: ${c.X}, y: ${c.Y}, n: ${c.N}, c_idx: ${c.CIdx},`);
  G.push('    plane: [');
  G.push(intLit(b64(c.Plane), '      '));
  G.push('    ],');
  G.push('    cplane: [');
  G.push(intLit(b64(c.CPlane), '      '));
  G.push('    ],');
  G.push(`    samples: [${c.Ref.join(', ')}],`);
  G.push('    avail: [');
  G.push(boolArr(c.Avail, '      '));
  G.push('    ] },');
}
G.push(']');
G.push('');

// ---------------------------------------------------------------------------
// reconstruct/golden.mbt
// ---------------------------------------------------------------------------
const R = [];
R.push('// Golden fixtures for the M3 single-block reconstruction chain.');
R.push('// Generated by tools/gen_reconstruct_golden.mjs from tools/reconstruct_golden.json');
R.push('// (the real upstream Go reconstructPlane, 8.6.x). Each case is a real');
R.push('// cabacWriter/encodeResidual CABAC bitstream plus the exact input plane,');
R.push('// prediction-only plane (cbf=false) and fully reconstructed plane (cbf=true).');
R.push('// The MoonBit port must reproduce them sample for sample.');
R.push('');
R.push('///|');
R.push('/// One reconstructPlane case. `bytes` is the CABAC substream; `coef` are');
R.push('/// the levels the upstream encoder wrote (for reference); `pred_plane` is');
R.push('/// the plane after intra prediction with cbf=false; `plane_out` is the full');
R.push('/// reconstruction with cbf=true (dequant -> inverse transform -> add).');
R.push('pub(all) struct ReconCase {');
R.push('  log2 : Int32');
R.push('  mode : Int32');
R.push('  c_idx : Int32');
R.push('  qp : Int32');
R.push('  x : Int32');
R.push('  y : Int32');
R.push('  stride : Int32');
R.push('  coef : Array[Int32]');
R.push('  bytes : Bytes');
R.push('  plane_in : Array[Int32]');
R.push('  pred_plane : Array[Int32]');
R.push('  plane_out : Array[Int32]');
R.push('}');
R.push('');
R.push('///|');
R.push('/// 17 reconstructPlane cases: log2 2..4, luma + chroma, qp 15..51,');
R.push('/// planar/DC/angular modes, real residual bitstreams.');
R.push('pub let recon_cases : Array[ReconCase] = [');
for (const c of g.recon) {
  R.push(`  { log2: ${c.Log2}, mode: ${c.Mode}, c_idx: ${c.CIdx}, qp: ${c.QP}, x: ${c.X}, y: ${c.Y}, stride: ${c.Stride},`);
  R.push(`    coef: [${c.Coef.join(', ')}],`);
  R.push('    bytes: Bytes::from_array([');
  R.push(bytesLit(b64(c.Bytes), '      '));
  R.push('    ]),');
  R.push('    plane_in: [');
  R.push(intLit(b64(c.PlaneIn), '      '));
  R.push('    ],');
  R.push('    pred_plane: [');
  R.push(intLit(b64(c.PredPlane), '      '));
  R.push('    ],');
  R.push('    plane_out: [');
  R.push(intLit(b64(c.PlaneOut), '      '));
  R.push('    ] },');
}
R.push(']');
R.push('');

const targets = [
  { file: 'hevc/geometry/golden.mbt', text: G.join('\n') + '\n' },
  { file: 'hevc/reconstruct/golden.mbt', text: R.join('\n') + '\n' },
];
const strip = t => t.replace(/\s+/g, '').replace(/,([\]}])/g, '$1');
let bad = 0;
for (const t of targets) {
  const target = path.join(root, t.file);
  if (check) {
    const cur = fs.existsSync(target) ? strip(fs.readFileSync(target, 'utf8')) : '';
    if (cur !== strip(t.text)) {
      console.error(`${t.file} is out of date; run node tools/gen_reconstruct_golden.mjs`);
      bad++;
    }
  } else {
    fs.writeFileSync(target, t.text);
  }
}
if (check) {
  if (bad) process.exit(1);
  console.log(`reconstruct golden is current (${g.min_tb_addr.length} mta, ${g.available.length} avail, ${g.predict_qp.length} qp, ${g.gather_ref.length} ref, ${g.recon.length} recon)`);
} else {
  console.log(`wrote hevc/geometry/golden.mbt and hevc/reconstruct/golden.mbt (${g.recon.length} recon cases)`);
}
