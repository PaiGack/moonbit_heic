#!/usr/bin/env node
// Bakes the loop-filter golden fixtures into hevc/loopfilter/golden.mbt.
//
// The values come from tools/loopfilter_golden.json, which is the REAL upstream
// Go gen2brain/h265 deblock()/applySAO() truth (export_loopfilter_golden_test.go,
// -tags noasm). tools/crosscheck_loopfilter.mjs verifies every one of those
// values against an independent from-the-spec JS transcription (126834 values,
// zero differences). This generator is thus the last, offline link of the
// trust chain: CI needs neither Go nor the network.
//
//   node tools/gen_loopfilter_golden.mjs            # rewrite the fixture
//   node tools/gen_loopfilter_golden.mjs --check    # verify the fixture is current
//
// Self-contained: reads only the committed tools/loopfilter_golden.json.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const g = JSON.parse(fs.readFileSync(path.join(root, 'tools/loopfilter_golden.json'), 'utf8'));
const dec = s => Array.from(Buffer.from(s, 'base64'));

const intLit = (arr, indent) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + arr.slice(i, i + 16).join(', ') + ',');
  return lines.join('\n');
};
const byteLit = (arr, indent) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + arr.slice(i, i + 16)
      .map(v => `b'\\x${v.toString(16).padStart(2, '0')}'`).join(', ') + ',');
  return lines.join('\n');
};
const boolLit = (arr, indent) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + arr.slice(i, i + 16).map(b => b ? 'true' : 'false').join(', ') + ',');
  return lines.join('\n');
};

const O = [];
O.push('// Golden fixtures for the M3 loop-filter layers (8.7.2 deblocking and');
O.push('// 8.7.3 SAO), generated by tools/gen_loopfilter_golden.mjs from the real');
O.push('// upstream Go deblock()/applySAO() truth, verified value-for-value by');
O.push('// tools/crosscheck_loopfilter.mjs against an independent from-the-spec');
O.push('// transcription. The MoonBit loopfilter package must reproduce every value.');
O.push('//');
O.push('// In/Out planes are raw 8-bit bytes. Int32 carriers are used for the pure');
O.push('// derivation tables (beta/tc, plan decisions, offsets), matching the spec.');
O.push('');

O.push('///|');
O.push('pub(all) struct BetaTcCase {');
O.push('  qp : Int32');
O.push('  bs : Int32');
O.push('  beta_off : Int32');
O.push('  tc_off : Int32');
O.push('  beta : Int32');
O.push('  tc : Int32');
O.push('}');
O.push('');
O.push('///|');
O.push('pub let beta_tc_cases : Array[BetaTcCase] = [');
for (const c of g.beta_tc) {
  O.push('  {');
  O.push(`    qp: ${c.QP}, bs: ${c.BS}, beta_off: ${c.BetaOff}, tc_off: ${c.TcOff},`);
  O.push(`    beta: ${c.Beta}, tc: ${c.Tc},`);
  O.push('  },');
}
O.push(']');
O.push('');

// Luma plan/apply cases (4x8 strips, Int32).
O.push('///|');
O.push('pub(all) struct LumaCase {');
O.push('  beta : Int32');
O.push('  tc : Int32');
O.push('  bit_depth : Int32');
O.push('  no_p : Bool');
O.push('  no_q : Bool');
O.push('  input : Array[Int32]');
O.push('  plan_mode : Int32');
O.push('  n_dp : Int32');
O.push('  n_dq : Int32');
O.push('  want : Array[Int32]');
O.push('}');
O.push('');
O.push('///|');
O.push('pub let luma_cases : Array[LumaCase] = [');
for (const c of g.luma) {
  O.push('  {');
  O.push(`    beta: ${c.Beta}, tc: ${c.Tc}, bit_depth: ${c.BitDepth},`);
  O.push(`    no_p: ${c.NoP}, no_q: ${c.NoQ},`);
  O.push('    input: ['); O.push(intLit(c.In, '      ')); O.push('    ],');
  O.push(`    plan_mode: ${c.PlanMode}, n_dp: ${c.NDp}, n_dq: ${c.NDq},`);
  O.push('    want: ['); O.push(intLit(c.Out, '      ')); O.push('    ],');
  O.push('  },');
}
O.push(']');
O.push('');

O.push('///|');
O.push('pub(all) struct ChromaCase {');
O.push('  tc : Int32');
O.push('  max_v : Int32');
O.push('  no_p : Bool');
O.push('  no_q : Bool');
O.push('  input : Array[Int32]');
O.push('  want : Array[Int32]');
O.push('}');
O.push('');
O.push('///|');
O.push('pub let chroma_cases : Array[ChromaCase] = [');
for (const c of g.chroma) {
  O.push('  {');
  O.push(`    tc: ${c.Tc}, max_v: ${c.MaxV}, no_p: ${c.NoP}, no_q: ${c.NoQ},`);
  O.push('    input: ['); O.push(intLit(c.In, '      ')); O.push('    ],');
  O.push('    want: ['); O.push(intLit(c.Out, '      ')); O.push('    ],');
  O.push('  },');
}
O.push(']');
O.push('');

O.push('///|');
O.push('pub(all) struct SaoBandCase {');
O.push('  band : Int32');
O.push('  shift : Int32');
O.push('  max_v : Int32');
O.push('  offset : Array[Int32]');
O.push('  src : Array[Int32]');
O.push('  want : Array[Int32]');
O.push('}');
O.push('');
O.push('///|');
O.push('pub let sao_band_cases : Array[SaoBandCase] = [');
for (const c of g.sao_band) {
  O.push('  {');
  O.push(`    band: ${c.Band}, shift: ${c.Shift}, max_v: ${c.MaxV},`);
  O.push('    offset: ['); O.push(intLit(c.Offset, '      ')); O.push('    ],');
  O.push('    src: ['); O.push(intLit(c.Src, '      ')); O.push('    ],');
  O.push('    want: ['); O.push(intLit(c.Dst, '      ')); O.push('    ],');
  O.push('  },');
}
O.push(']');
O.push('');

O.push('///|');
O.push('pub(all) struct SaoEdgeCase {');
O.push('  max_v : Int32');
O.push('  offset : Array[Int32]');
O.push('  src : Array[Int32]');
O.push('  na : Array[Int32]');
O.push('  nb : Array[Int32]');
O.push('  want : Array[Int32]');
O.push('}');
O.push('');
O.push('///|');
O.push('pub let sao_edge_cases : Array[SaoEdgeCase] = [');
for (const c of g.sao_edge) {
  O.push('  {');
  O.push(`    max_v: ${c.MaxV},`);
  O.push('    offset: ['); O.push(intLit(c.Offset, '      ')); O.push('    ],');
  O.push('    src: ['); O.push(intLit(c.Src, '      ')); O.push('    ],');
  O.push('    na: ['); O.push(intLit(c.Na, '      ')); O.push('    ],');
  O.push('    nb: ['); O.push(intLit(c.Nb, '      ')); O.push('    ],');
  O.push('    want: ['); O.push(intLit(c.Dst, '      ')); O.push('    ],');
  O.push('  },');
}
O.push(']');
O.push('');

// Whole-frame cases: each plane is its own `pub let` in its own `///|`
// segment, so no single text segment approaches MoonBit's line limit (the
// 7 frames together are ~1.8 MB of raw bytes). frame_cases then references
// those bindings instead of inlining every byte into one huge literal.
const planeFields = ['y', 'cb', 'cr', 'deb_y', 'deb_cb', 'deb_cr', 'sao_y', 'sao_cb', 'sao_cr'];
const goPlanes = ['Y', 'Cb', 'Cr', 'DebY', 'DebCb', 'DebCr', 'SaoY', 'SaoCb', 'SaoCr'];
for (let fi = 0; fi < g.frames.length; fi++) {
  for (let pi = 0; pi < planeFields.length; pi++) {
    O.push('///|');
    O.push(`pub let frame_${fi}_${planeFields[pi]} : Bytes = Bytes::from_array([`);
    O.push(byteLit(dec(g.frames[fi][goPlanes[pi]]), '  '));
    O.push('])');
    O.push('');
  }
}

O.push('///|');
O.push('pub(all) struct FrameCase {');
O.push('  label : String');
O.push('  width : Int32');
O.push('  height : Int32');
O.push('  ctb_log2 : Int32');
O.push('  qp_y : Int32');
O.push('  beta_off : Int32');
O.push('  tc_off : Int32');
O.push('  deblock_off : Bool');
O.push('  sao_on : Bool');
O.push('  sao_type : Int32');
O.push('  sao_class : Int32');
O.push('  sao_band : Int32');
O.push('  sao_offset : Array[Int32]');
O.push('  qp_field : Array[Int32]');
O.push('  no_filter : Array[Bool]');
O.push('  y : Bytes');
O.push('  cb : Bytes');
O.push('  cr : Bytes');
O.push('  deb_y : Bytes');
O.push('  deb_cb : Bytes');
O.push('  deb_cr : Bytes');
O.push('  sao_y : Bytes');
O.push('  sao_cb : Bytes');
O.push('  sao_cr : Bytes');
O.push('}');
O.push('');
O.push('///|');
O.push('pub let frame_cases : Array[FrameCase] = [');
for (let fi2 = 0; fi2 < g.frames.length; fi2++) {
  const f = g.frames[fi2];
  O.push('  {');
  O.push(`    label: "${f.Label}",`);
  O.push(`    width: ${f.W}, height: ${f.H}, ctb_log2: ${f.CtbLog2},`);
  O.push(`    qp_y: ${f.QpY}, beta_off: ${f.BetaOff}, tc_off: ${f.TcOff},`);
  O.push(`    deblock_off: ${f.DeblockOff}, sao_on: ${f.SaoOn},`);
  O.push(`    sao_type: ${f.SaoType}, sao_class: ${f.SaoClass}, sao_band: ${f.SaoBand},`);
  O.push('    sao_offset: ['); O.push(intLit(f.SaoOffset, '      ')); O.push('    ],');
  O.push('    qp_field: ['); O.push(intLit(f.QpField, '      ')); O.push('    ],');
  O.push('    no_filter: ['); O.push(boolLit(f.NoFilter, '      ')); O.push('    ],');
  for (let pi = 0; pi < planeFields.length; pi++) {
    O.push(`    ${planeFields[pi]}: frame_${fi2}_${planeFields[pi]},`);
  }
  O.push('  },');
}
O.push(']');
O.push('');

const generated = O.join('\n') + '\n';
const target = path.join(root, 'hevc/loopfilter/golden.mbt');
const strip = t => t.replace(/\s+/g, '').replace(/,([\]}])/g, '$1');
if (process.argv.includes('--check')) {
  const current = strip(fs.readFileSync(target, 'utf8'));
  if (current !== strip(generated)) {
    console.error('hevc/loopfilter/golden.mbt is out of date; run node tools/gen_loopfilter_golden.mjs');
    process.exit(1);
  }
  console.log(`loopfilter golden is current (${g.beta_tc.length} betaTc, ${g.luma.length} luma, ` +
    `${g.chroma.length} chroma, ${g.sao_band.length} sao_band, ${g.sao_edge.length} sao_edge, ` +
    `${g.frames.length} whole frames)`);
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, generated);
  console.log(`wrote hevc/loopfilter/golden.mbt (${g.frames.length} whole frames)`);
}
