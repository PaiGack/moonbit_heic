#!/usr/bin/env node
// Regenerates hevc/residual/golden.mbt: byte-exact fixtures for the M3
// residual-coefficient syntax layer (7.3.8.11).
//
// The fixture data comes from tools/residual_golden.json, which the real
// upstream Go encoder produced (export_residual_golden_test.go in the
// gen2brain/h265 checkout). tools/crosscheck_residual.mjs holds that JSON
// value-for-value against an independent, from-the-spec JS transcription of
// both the CABAC decoder and the residual syntax (122488 values, zero
// differences during development), so the fixture is trustworthy without a
// Go toolchain or network at CI time.
//
//   node tools/gen_residual_golden.mjs            # rewrite the fixture
//   node tools/gen_residual_golden.mjs --check    # verify it is current
//
// Self-contained: reads only the committed JSON and re-emits MoonBit literals.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const g = JSON.parse(fs.readFileSync(path.join(root, 'tools/residual_golden.json'), 'utf8'));
const check = process.argv.includes('--check');

function bytesLit(arr, indent) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + arr.slice(i, i + 16).map(b => `b'\\x${b.toString(16).padStart(2, '0')}'`).join(', ') + ',');
  return lines.join('\n');
}
function intLit(arr, indent, width = 16) {
  const lines = [];
  for (let i = 0; i < arr.length; i += width)
    lines.push(indent + arr.slice(i, i + width).join(', ') + ',');
  return lines.join('\n');
}
const b64 = s => Array.from(Buffer.from(s, 'base64'));

const out = [];
out.push('// Golden fixtures for the M3 residual-coefficient syntax layer,');
out.push('// generated by tools/gen_residual_golden.mjs from tools/residual_golden.json');
out.push('// (the real upstream Go encoder) and held value-for-value against an');
out.push('// independent JS transcription by tools/crosscheck_residual.mjs.');
out.push('// The MoonBit residual package must reproduce every value exactly.');
out.push('');
out.push('///|');
out.push('/// One scanIndex derivation case.');
out.push('pub(all) struct ScanIndexCase {');
out.push('  log2_size : Int32');
out.push('  c_idx : Int32');
out.push('  mode : Int32');
out.push('  intra : Bool');
out.push('  chroma : Int32');
out.push('  want : Int32');
out.push('}');
out.push('');
out.push('///|');
out.push('/// One lastSigCoeffCtx derivation case.');
out.push('pub(all) struct LastCtxCase {');
out.push('  log2_size : Int32');
out.push('  c_idx : Int32');
out.push('  bin_idx : Int32');
out.push('  want : Int32');
out.push('}');
out.push('');
out.push('///|');
out.push('/// One residual_coding() bitstream produced by the upstream Go encoder,');
out.push('/// with the coefficient levels it must decode back into.');
out.push('pub(all) struct ResidualCase {');
out.push('  log2_size : Int32');
out.push('  c_idx : Int32');
out.push('  pred_mode : Int32');
out.push('  intra : Bool');
out.push('  sign_hiding : Bool');
out.push('  bytes : Bytes');
out.push('  coef : Array[Int32]');
out.push('}');
out.push('');

// ---- scan_index cases ---------------------------------------------------
out.push('///|');
out.push('pub let scan_index_cases : Array[ScanIndexCase] = [');
for (const t of g.scan_index)
  out.push(`  { log2_size: ${t.Log2}, c_idx: ${t.CIdx}, mode: ${t.Mode}, intra: ${t.Intra}, chroma: ${t.Chroma}, want: ${t.Want} },`);
out.push(']');
out.push('');

// ---- last_sig_coeff_ctx cases -------------------------------------------
out.push('///|');
out.push('pub let last_ctx_cases : Array[LastCtxCase] = [');
for (const t of g.last_sig_coeff_ctx)
  out.push(`  { log2_size: ${t.Log2}, c_idx: ${t.CIdx}, bin_idx: ${t.Bin}, want: ${t.Want} },`);
out.push(']');
out.push('');

// ---- full sigCoeffCtx traversal, flattened in the documented order ------
out.push('///|');
out.push('/// sigCoeffCtx for the fixed traversal: log2=2..5, cIdx in {0,1},');
out.push('/// scan=0..2, csbf=0..3, y=0..n-1, x=0..n-1 (see crosscheck).');
out.push('pub let sig_coeff_ctx_want : Array[Int32] = [');
out.push(intLit(g.sig_coeff_ctx, '  '));
out.push(']');
out.push('');
out.push('///|');
out.push('/// SigCtxSet::at for the fixed traversal: log2=2..5, cIdx in {0,1,2},');
out.push('/// scan=0..2, csbf=0..3, yS, xS over the sub-block grid, y=0..3, x=0..3.');
out.push('pub let sig_ctx_set_want : Array[Int32] = [');
out.push(intLit(g.sig_ctx_set, '  '));
out.push(']');
out.push('');

// ---- residual_coding bitstreams -----------------------------------------
out.push('///|');
out.push('pub let residual_cases : Array[ResidualCase] = [');
for (const c of g.cases) {
  out.push('  {');
  out.push(`    log2_size: ${c.Log2}, c_idx: ${c.CIdx}, pred_mode: ${c.PredMode}, intra: ${c.Intra}, sign_hiding: ${c.SignHiding},`);
  out.push('    bytes: Bytes::from_array([');
  out.push(bytesLit(b64(c.Bytes), '      '));
  out.push('    ]),');
  out.push('    coef: [');
  out.push(intLit(c.Coef, '      '));
  out.push('    ],');
  out.push('  },');
}
out.push(']');
out.push('');

const generated = out.join('\n');
const target = path.join(root, 'hevc/residual/golden.mbt');

// --check verifies DATA, not bytes: moon fmt is free to reflow the generated
// literals, so compare the ordered numeric payload the fixture encodes with
// the authoritative truth re-derived from the Go JSON. Every literal in the
// fixture is a number, a boolean, or a b'\\xNN' byte; extracting those in
// order gives a format-independent fingerprint.
function numericFingerprint(text) {
  const toks = [];
  // Work on the data section only, with comments and declaration headers
  // stripped: those carry spec section numbers that are not payload.
  const start = text.indexOf('pub let scan_index_cases');
  if (start < 0) throw new Error('no data section in golden.mbt');
  const body = text.slice(start)
    .split('\n')
    .filter(l => !l.trim().startsWith('//') && !l.includes('pub let ') &&
                 !l.includes('pub(all) struct'))
    .join('\n');
  // Booleans, hex byte literals, and signed decimal integers, in source order.
  const re = /\b(true|false)\b|b'\\x([0-9a-f]{2})'|(?<![A-Za-z0-9_])(-?\d+)(?![A-Za-z0-9_])/g;
  let m;
  while ((m = re.exec(body)) !== null) {
    if (m[1] !== undefined) toks.push(m[1]);
    else if (m[2] !== undefined) toks.push('x' + m[2]);
    else toks.push(m[3]);
  }
  return toks;
}

// Rebuild the expected fingerprint from the JSON truth, in exactly the order
// the generator emits it.
function truthFingerprint() {
  const t = [];
  const push = (...xs) => { for (const x of xs) t.push(String(x)); };
  for (const c of g.scan_index)
    push(c.Log2, c.CIdx, c.Mode, c.Intra, c.Chroma, c.Want);
  for (const c of g.last_sig_coeff_ctx)
    push(c.Log2, c.CIdx, c.Bin, c.Want);
  for (const v of g.sig_coeff_ctx) push(v);
  for (const v of g.sig_ctx_set) push(v);
  for (const c of g.cases) {
    push(c.Log2, c.CIdx, c.PredMode, c.Intra, c.SignHiding);
    for (const b of b64(c.Bytes)) push('x' + b.toString(16).padStart(2, '0'));
    for (const v of c.Coef) push(v);
  }
  return t;
}

if (check) {
  const current = fs.readFileSync(target, 'utf8');
  const got = numericFingerprint(current);
  const want = truthFingerprint();
  if (got.length !== want.length) {
    console.error(`hevc/residual/golden.mbt payload length ${got.length}, expected ${want.length}`);
    process.exit(1);
  }
  for (let i = 0; i < want.length; i++) {
    if (got[i] !== want[i]) {
      console.error(`hevc/residual/golden.mbt drift at token ${i}: got ${got[i]}, want ${want[i]}`);
      process.exit(1);
    }
  }
  console.log(`gen_residual_golden --check: ${want.length} tokens current (${g.cases.length} bitstreams, ${g.sig_coeff_ctx.length + g.sig_ctx_set.length} context values)`);
} else {
  fs.writeFileSync(target, generated);
  console.log(`wrote ${target}: ${g.cases.length} bitstreams, ${g.scan_index.length} scanIndex, ${g.last_sig_coeff_ctx.length} lastCtx, ${g.sig_coeff_ctx.length} sigCtx, ${g.sig_ctx_set.length} sigSet`);
}
