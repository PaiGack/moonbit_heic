#!/usr/bin/env node
// Regenerates hevc/ctu/golden.mbt: whole-I-frame byte-exact fixtures for the
// M3 CTU quadtree/TU/PU driver.
//
// The fixture data comes from tools/frame_golden.json, produced by the REAL
// upstream Go decoder (tools/export_frame_golden_test.go, run in a
// gen2brain/h265 checkout with -tags noasm): each small I-frame stream is
// decoded by DecodeNAL + Flush into its final planar YUV, and the decoder's
// output is asserted byte-for-byte against the upstream *_ref.yuv where one
// ships. Each case also carries `trace`: the ordered list of transform blocks
// the real codingTreeUnit reconstructed (x, y, log2, cIdx, mode, cbf, qp),
// captured by a test-only hook, which is an oracle for debugging bin order.
//
// tools/crosscheck_frame.mjs verifies the fixture's stream/YUV fingerprints
// and the trace shape against an independent JS computation. The MoonBit port
// (hevc/ctu + decode_i_frame) must reproduce every YUV sample. CI needs no
// Go/network.
//
//   node tools/gen_frame_golden.mjs            # rewrite the fixture
//   node tools/gen_frame_golden.mjs --check    # verify it is current
//
// Self-contained: reads only the committed JSON and re-emits MoonBit literals.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const raw = JSON.parse(fs.readFileSync(path.join(root, 'tools/frame_golden.json'), 'utf8'));
const check = process.argv.includes('--check');

const b64 = s => Array.from(Buffer.from(s, 'base64'));
const boolLit = v => v ? 'true' : 'false';
function bytesLit(arr, indent) {
  const lines = [];
  for (let i = 0; i < arr.length; i += 16)
    lines.push(indent + arr.slice(i, i + 16).map(b => `b'\\x${b.toString(16).padStart(2, '0')}'`).join(', ') + ',');
  return lines.join('\n') || indent;
}

const L = [];
L.push('// Golden fixtures for the M3 whole-picture CTU reconstruction.');
L.push('// Generated by tools/gen_frame_golden.mjs from tools/frame_golden.json');
L.push('// (the REAL upstream Go decoder, -tags noasm). Each case is a complete');
L.push('// Annex B I-frame stream plus the exact planar Y/Cb/Cr output; the MoonBit');
L.push('// decode_i_frame must reproduce every sample. `trace` is the ordered list of');
L.push('// transform blocks the real codingTreeUnit reconstructed.');
L.push('');
L.push('///|');
L.push('/// One transform block the upstream CTU loop reconstructed.');
L.push('pub(all) struct TbTrace {');
L.push('  x : Int32');
L.push('  y : Int32');
L.push('  log2 : Int32');
L.push('  c_idx : Int32');
L.push('  mode : Int32');
L.push('  cbf : Bool');
L.push('  qp : Int32');
L.push('}');
L.push('');
L.push('///|');
L.push('/// One whole I frame: stream bytes, expected planar YUV, dimensions, and');
L.push('/// the transform-block trace (an oracle for debugging bin order).');
L.push('pub(all) struct FrameCase {');
L.push('  name : String');
L.push('  stream : Bytes');
L.push('  yuv : Bytes');
L.push('  width : Int32');
L.push('  height : Int32');
L.push('  has_ref : Bool');
L.push('  trace : Array[TbTrace]');
L.push('}');
L.push('');
L.push('///|');
L.push(`/// ${raw.cases.length} single-slice I frames: 16x16 .. 64x64, quadtree depths,`);
L.push('/// 4/8/16/32 TUs, cu_qp_delta, sign hiding, strong intra smoothing,');
L.push('/// multi-CTB neighbour state.');
L.push('pub let frame_cases : Array[FrameCase] = [');
for (const c of raw.cases) {
  L.push('  {');
  L.push(`    name: ${JSON.stringify(c.name)},`);
  L.push(`    stream: b"${b64(c.stream).map(b => `\\x${b.toString(16).padStart(2, '0')}`).join('')}",`);
  L.push(`    yuv: b"${b64(c.yuv).map(b => `\\x${b.toString(16).padStart(2, '0')}`).join('')}",`);
  L.push(`    width: ${c.width},`);
  L.push(`    height: ${c.height},`);
  L.push(`    has_ref: ${boolLit(c.has_ref)},`);
  L.push('    trace: [');
  for (const t of c.trace) {
    L.push(`      { x: ${t.x}, y: ${t.y}, log2: ${t.log2}, c_idx: ${t.cidx}, mode: ${t.mode}, cbf: ${boolLit(t.cbf)}, qp: ${t.qp}, },`);
  }
  L.push('    ],');
  L.push('  },');
}
L.push(']');
L.push('');

const out = L.join('\n');
const target = path.join(root, 'hevc/ctu/golden.mbt');
if (check) {
  const cur = fs.readFileSync(target, 'utf8');
  if (cur !== out) {
    console.error('hevc/ctu/golden.mbt is stale; run node tools/gen_frame_golden.mjs');
    process.exit(1);
  }
  console.log(`frame golden OK (${raw.cases.length} cases, ${raw.cases.reduce((n, c) => n + c.trace.length, 0)} TBs)`);
} else {
  fs.writeFileSync(target, out);
  console.log(`wrote ${target} (${raw.cases.length} cases, ${out.length} bytes)`);
}
